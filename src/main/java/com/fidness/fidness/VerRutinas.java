private void cargarRutinas() {

    javax.swing.DefaultListModel<String> modelo =
            new javax.swing.DefaultListModel<>();

    for (Rutina rutina : GestorRutinas.obtenerRutinas()) {
        modelo.addElement(rutina.getNombreRutina());
    }

    listaRutinas.setModel(modelo);
}
