    private void btnVerRutinaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerRutinaActionPerformed
int posicion = listaRutinas.getSelectedIndex();

if (posicion == -1) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Seleccione una rutina primero."
    );
    return;
}

Rutina rutina = GestorRutinas.obtenerRutinas().get(posicion);

javax.swing.JOptionPane.showMessageDialog(
        this,
        rutina.mostrarRutina(),
        "Rutina",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
);        // TODO add your handling code here:
    }//GEN-LAST:event_btnVerRutinaActionPerformed

