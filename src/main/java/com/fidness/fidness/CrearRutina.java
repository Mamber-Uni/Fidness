    private void btnAgregarEjercicioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarEjercicioActionPerformed
String nombreSeleccionado = listaEjerciciosRutina.getSelectedValue();

if (nombreSeleccionado == null) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Seleccione un ejercicio primero."
    );
    return;
}

java.util.ArrayList<Ejercicio> ejercicios = Datos.obtenerEjercicios();

for (Ejercicio ejercicio : ejercicios) {

    if (ejercicio.getNombre().equals(nombreSeleccionado)) {

        rutinaActual.agregarEjercicio(ejercicio);

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Ejercicio agregado a la rutina."
        );

        break;
    }
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnAgregarEjercicioActionPerformed

    private void btnGuardarRutinaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarRutinaActionPerformed
String nombreRutina = txtNombreRutina.getText();

try {

    if (nombreRutina.isEmpty()) {
        throw new Exception("Debe escribir un nombre para la rutina.");
    }

    if (rutinaActual.getListaEjercicios().isEmpty()) {
        throw new Exception("Debe agregar al menos un ejercicio.");
    }

    Rutina rutinaGuardada = new Rutina(nombreRutina);

    for (Ejercicio ejercicio : rutinaActual.getListaEjercicios()) {
        rutinaGuardada.agregarEjercicio(ejercicio);
    }

    GestorRutinas.guardarRutina(rutinaGuardada);
    
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Rutina guardada correctamente.\n\n"
            + rutinaGuardada.mostrarRutina()
    );

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            e.getMessage()
    );
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarRutinaActionPerformed

