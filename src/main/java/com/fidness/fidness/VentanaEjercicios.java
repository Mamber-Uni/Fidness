private void cargarEjercicios(String tipo) {

    java.util.ArrayList<Ejercicio> ejercicios = Datos.obtenerEjercicios();

    javax.swing.DefaultListModel<String> modelo =
            new javax.swing.DefaultListModel<>();

    for (Ejercicio ejercicio : ejercicios) {

        if (tipo.equals("Todos")
                || ejercicio.getTipo().equals(tipo)) {

            modelo.addElement(ejercicio.getNombre());
        }
    }

    listaEjercicios.setModel(modelo);
}
