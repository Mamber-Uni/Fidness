    private void btnVolverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVolverActionPerformed
String nombreSeleccionado = listaEjercicios.getSelectedValue();

if (nombreSeleccionado == null) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Seleccione un ejercicio primero."
    );
    return;
}

java.util.ArrayList<Ejercicio> ejercicios = Datos.obtenerEjercicios();

for (Ejercicio ejercicio : ejercicios) {

    if (ejercicio.getNombre().equals(nombreSeleccionado)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                ejercicio.mostrarInformacion(),
                "Información del ejercicio",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        break;
    }
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnVolverActionPerformed

